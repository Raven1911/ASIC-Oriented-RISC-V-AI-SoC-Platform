static void OV5640_WriteReg(I2CDriver_t* i2c_drv, uint8_t reg_high, uint8_t reg_low, uint8_t val)
{
    I2C_select_slave(i2c_drv, OV5640_ADDR, false, false);
    I2C_write(i2c_drv, reg_high);
    I2C_write(i2c_drv, reg_low);
    I2C_write(i2c_drv, val);
    I2C_stop(i2c_drv);
}

static void OV5640_WriteTable(I2CDriver_t* i2c_drv,
                              const OV5640_RegSetting* table,
                              int num_regs)
{
    for (int i = 0; i < num_regs; i++) {
        OV5640_WriteReg(i2c_drv,
                        table[i].reg_high,
                        table[i].reg_low,
                        table[i].val);
        delay(1);
    }
}

void OV5640_Init(I2CDriver_t* i2c_drv) {
    // Uart_println("Initializing OV5640...");
    
    int num_regs = sizeof(ov5640_vga_rgb565) / sizeof(OV5640_RegSetting);

    OV5640_WriteTable(i2c_drv, ov5640_vga_rgb565, num_regs);
    
    // Uart_println("OV5640 Initialization Complete!");
}

void OV5640_ResetByI2C(I2CDriver_t* i2c_drv) {
    Uart_println("Sending OV5640 I2C software reset...");
    OV5640_WriteReg(i2c_drv,
                    OV5640_SYS_CTRL0_REG_HIGH,
                    OV5640_SYS_CTRL0_REG_LOW,
                    OV5640_SYS_CTRL0_SW_RESET);
    delay(100);
    Uart_println("OV5640 I2C reset command done.");
}

void OV5640_ResetVideoIP(void) {
    Uart_println("Resetting video streaming IP...");
    VideoStreaming_enable(&video_streaming, false);
    delay(100);
    VideoStreaming_enable(&video_streaming, true);
    Uart_println("Video streaming IP reset done.");
}

void OV5640_ToggleVideoIP(void) {
    bool is_enabled = VideoStreaming_is_enabled(&video_streaming);

    VideoStreaming_enable(&video_streaming, !is_enabled);

    if (is_enabled) {
        Uart_println("Video streaming IP disabled.");
    } else {
        Uart_println("Video streaming IP enabled.");
    }
}

void OV5640_ApplyDefaultIsp(I2CDriver_t* i2c_drv)
{
    Uart_println("Applying OV5640 default ISP preset...");
    OV5640_WriteReg(i2c_drv, 0x50, 0x00, 0xa7);
    OV5640_WriteReg(i2c_drv, 0x50, 0x01, 0xa3);
    OV5640_WriteReg(i2c_drv, 0x51, 0x96, 0x03);
    OV5640_WriteReg(i2c_drv, 0x34, 0x06, 0x00);
    Uart_println("OV5640 default ISP preset done.");
}

