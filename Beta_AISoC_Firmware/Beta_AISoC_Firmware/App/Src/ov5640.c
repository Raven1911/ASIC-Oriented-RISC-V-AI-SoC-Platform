void OV5640_Config(I2CDriver_t* i2c_drv) {
    Uart_println("Stopping video streaming...");
    VideoStreaming_enable(&video_streaming, false);
    delay(100);

    Uart_println("Configuring OV5640...");
    OV5640_Init(i2c_drv);
    delay(200);

    Uart_println("Starting video streaming...");
    VideoStreaming_enable(&video_streaming, true);
    Uart_println("OV5640 config done.");
}
